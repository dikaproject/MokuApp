//! The signature of a release: ECDSA P-256 over the SHA-256 of `moku-setup.exe`, checked with
//! Windows CNG (`BCryptImportKeyPair` with an `ECCPUBLICBLOB` + `BCryptVerifySignature`), so no
//! crypto crate is needed. The checksum file alone only proves the download is intact (anyone
//! who can replace the installer on GitHub can replace the checksum next to it); the signature
//! proves it was made with the private key the maintainer keeps off GitHub. The matching public
//! key is a constant in the program: `moku_core::release::UPDATE_PUBLIC_KEY`.

use windows::Win32::Security::Cryptography::{
    BCRYPT_ALG_HANDLE, BCRYPT_ECCPUBLIC_BLOB, BCRYPT_ECDSA_P256_ALGORITHM, BCRYPT_ECDSA_PUBLIC_P256_MAGIC, BCRYPT_FLAGS, BCRYPT_KEY_HANDLE, BCRYPT_OPEN_ALGORITHM_PROVIDER_FLAGS, BCryptCloseAlgorithmProvider,
    BCryptDestroyKey, BCryptImportKeyPair, BCryptOpenAlgorithmProvider, BCryptVerifySignature,
};

/// Is `signature` (r || s, 64 bytes) a valid ECDSA P-256 signature of `digest` by the key
/// `public_xy` (X || Y, 64 bytes)? `Err` says why not (the updater logs it and refuses).
pub fn verify(public_xy: &[u8; 64], digest: &[u8; 32], signature: &[u8; 64]) -> Result<(), String> {
    // BCRYPT_ECCKEY_BLOB { dwMagic, cbKey } followed by X and Y, big-endian as in the key.
    let mut blob = Vec::with_capacity(72);
    blob.extend_from_slice(&BCRYPT_ECDSA_PUBLIC_P256_MAGIC.to_le_bytes());
    blob.extend_from_slice(&32u32.to_le_bytes());
    blob.extend_from_slice(public_xy);
    // SAFETY: plain CNG calls on handles created and destroyed here.
    unsafe {
        let mut alg = BCRYPT_ALG_HANDLE::default();
        let st = BCryptOpenAlgorithmProvider(&mut alg, BCRYPT_ECDSA_P256_ALGORITHM, None, BCRYPT_OPEN_ALGORITHM_PROVIDER_FLAGS(0));
        if st.is_err() {
            return Err(format!("BCryptOpenAlgorithmProvider(ECDSA_P256) failed (0x{:08X})", st.0));
        }
        let mut key = BCRYPT_KEY_HANDLE::default();
        let st = BCryptImportKeyPair(alg, None, BCRYPT_ECCPUBLIC_BLOB, &mut key, &blob, 0);
        if st.is_err() {
            let _ = BCryptCloseAlgorithmProvider(alg, 0);
            return Err(format!("the public key is not a valid P-256 point (0x{:08X})", st.0));
        }
        let st = BCryptVerifySignature(key, None, digest, signature, BCRYPT_FLAGS(0));
        let _ = BCryptDestroyKey(key);
        let _ = BCryptCloseAlgorithmProvider(alg, 0);
        if st.is_err() { Err("the signature does not match".to_string()) } else { Ok(()) }
    }
}

/// What the updater does with a release: `key` is the built-in public key (hex), `sig_text` the
/// content of `moku-setup.exe.sig` (`None` = the release has none), `digest` the SHA-256 of the
/// installer. Every way of lacking a good signature is an `Err`.
pub fn verify_release(key: Option<&str>, sig_text: Option<&str>, digest: &[u8; 32]) -> Result<(), String> {
    let key = key.ok_or("this build has no public key to check signatures with")?;
    let key = moku_core::release::parse_public_key(key).ok_or("the built-in public key is malformed")?;
    let sig_text = sig_text.ok_or("the release has no signature (moku-setup.exe.sig)")?;
    let sig = moku_core::release::parse_signature_file(sig_text).ok_or("the signature file is not 128 hex digits")?;
    verify(&key, digest, &sig)
}

#[cfg(test)]
pub mod test_key {
    //! A throw-away key pair generated by the test itself (CNG), to sign with.

    use windows::Win32::Security::Cryptography::{
        BCRYPT_ALG_HANDLE, BCRYPT_ECCPUBLIC_BLOB, BCRYPT_ECDSA_P256_ALGORITHM, BCRYPT_FLAGS, BCRYPT_KEY_HANDLE, BCRYPT_OPEN_ALGORITHM_PROVIDER_FLAGS, BCryptDestroyKey, BCryptExportKey, BCryptFinalizeKeyPair, BCryptGenerateKeyPair,
        BCryptOpenAlgorithmProvider, BCryptSignHash,
    };

    pub struct TestKey {
        key: BCRYPT_KEY_HANDLE,
        /// X || Y.
        pub public: [u8; 64],
    }

    impl TestKey {
        pub fn generate() -> TestKey {
            unsafe {
                let mut alg = BCRYPT_ALG_HANDLE::default();
                assert!(BCryptOpenAlgorithmProvider(&mut alg, BCRYPT_ECDSA_P256_ALGORITHM, None, BCRYPT_OPEN_ALGORITHM_PROVIDER_FLAGS(0)).is_ok());
                let mut key = BCRYPT_KEY_HANDLE::default();
                assert!(BCryptGenerateKeyPair(alg, &mut key, 256, 0).is_ok());
                assert!(BCryptFinalizeKeyPair(key, 0).is_ok());
                let mut buf = [0u8; 72];
                let mut n = 0u32;
                assert!(BCryptExportKey(key, None, BCRYPT_ECCPUBLIC_BLOB, Some(&mut buf), &mut n, 0).is_ok());
                assert_eq!(n, 72);
                let mut public = [0u8; 64];
                public.copy_from_slice(&buf[8..72]);
                TestKey { key, public }
            }
        }

        pub fn public_hex(&self) -> String {
            self.public.iter().map(|b| format!("{b:02x}")).collect()
        }

        pub fn sign(&self, digest: &[u8; 32]) -> [u8; 64] {
            let mut sig = [0u8; 64];
            let mut n = 0u32;
            unsafe {
                assert!(BCryptSignHash(self.key, None, digest, Some(&mut sig), &mut n, BCRYPT_FLAGS(0)).is_ok());
            }
            assert_eq!(n, 64);
            sig
        }

        pub fn sig_file(&self, digest: &[u8; 32]) -> String {
            let s: String = self.sign(digest).iter().map(|b| format!("{b:02x}")).collect();
            format!("{s}\n")
        }
    }

    impl Drop for TestKey {
        fn drop(&mut self) {
            unsafe {
                let _ = BCryptDestroyKey(self.key);
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::test_key::TestKey;
    use super::*;
    use crate::features::update::sha256;

    fn digest_of(data: &[u8]) -> [u8; 32] {
        sha256::digest(data).unwrap()
    }

    /// A signature made by `app/tools/release-key.ps1` (.NET ECDsaCng) with a throw-away key (its
    /// private half was discarded) for the bytes `moku test fixture installer`: the script and
    /// the verifier agree on the formats (P1363 r || s, hex, X || Y public key).
    #[test]
    fn a_signature_made_by_the_release_script_verifies() {
        const PUBLIC: &str = "8a422e8bc6910fee6beac70047923826e7674f7c281864be5ecfa4da67141e3c7415e4fe5342abd4c9ae4f4964ab90108b6f70a9a244065a46869078de4d6b2b";
        const SIG_FILE: &str = "5c93b001599c843fd775996470d3da7c847f9976eaba3467b3b41d798148b55480ece80c8b5e147fa89b8bcfa78281cf3fd6e8937c58a4f4803d236be3435ddb\n";
        let d = digest_of(b"moku test fixture installer");
        assert_eq!(verify_release(Some(PUBLIC), Some(SIG_FILE), &d), Ok(()));
        // The same signature does not cover a different installer.
        assert!(verify_release(Some(PUBLIC), Some(SIG_FILE), &digest_of(b"moku test fixture installer!")).is_err());
    }

    #[test]
    fn a_good_signature_is_accepted() {
        let k = TestKey::generate();
        let d = digest_of(b"the installer");
        let sig = k.sign(&d);
        assert_eq!(verify(&k.public, &d, &sig), Ok(()));
        // Through the release path: key as hex, signature file text with a newline.
        assert_eq!(verify_release(Some(&k.public_hex()), Some(&k.sig_file(&d)), &d), Ok(()));
        // ECDSA signatures are randomised: a second signature differs and is also good.
        assert_eq!(verify(&k.public, &d, &k.sign(&d)), Ok(()));
    }

    #[test]
    fn a_bad_signature_is_refused() {
        let k = TestKey::generate();
        let d = digest_of(b"the installer");
        let good = k.sign(&d);
        // One flipped bit.
        let mut bad = good;
        bad[10] ^= 1;
        assert!(verify(&k.public, &d, &bad).is_err(), "a damaged signature");
        // A different installer (the digest changed): the old signature does not cover it.
        let other = digest_of(b"another installer");
        assert!(verify(&k.public, &other, &good).is_err(), "signature of another file");
        // Signed with another key.
        let k2 = TestKey::generate();
        assert!(verify(&k2.public, &d, &good).is_err(), "signature by another key");
        assert!(verify_release(Some(&k2.public_hex()), Some(&k.sig_file(&d)), &d).is_err());
        // All zeros, and all 0xff.
        assert!(verify(&k.public, &d, &[0u8; 64]).is_err());
        assert!(verify(&k.public, &d, &[0xffu8; 64]).is_err());
        // A public key that is not a point on the curve.
        assert!(verify(&[1u8; 64], &d, &good).is_err());
    }

    #[test]
    fn a_missing_signature_is_refused() {
        let k = TestKey::generate();
        let d = digest_of(b"the installer");
        // The release has no .sig at all.
        let e = verify_release(Some(&k.public_hex()), None, &d).unwrap_err();
        assert!(e.contains("no signature"), "{e}");
        // An empty, truncated or garbage .sig.
        for text in ["", "\n", "not a signature", &k.sig_file(&d)[..100], "00"] {
            assert!(verify_release(Some(&k.public_hex()), Some(text), &d).is_err(), "{text:?}");
        }
        // No public key built in (the shipped source tree): nothing can be verified.
        let e = verify_release(None, Some(&k.sig_file(&d)), &d).unwrap_err();
        assert!(e.contains("no public key"), "{e}");
        assert!(verify_release(Some("zz"), Some(&k.sig_file(&d)), &d).is_err(), "a malformed built-in key");
    }
}
