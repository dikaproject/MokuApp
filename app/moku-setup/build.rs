//! Embeds the release binaries into `moku-setup.exe` (a packaging step, see `tools/release.ps1`).
//!
//! `MOKU_SETUP_PAYLOAD` names a folder that holds `moku.exe`, `moku-settings.exe`, `mokuctl.exe`
//! and any other files to install (e.g. `docs\claude-code-hook.md`). Each file is compressed with
//! LZMS (Windows Compression API) into `OUT_DIR` and pulled in with `include_bytes!`.
//!
//! Without the variable the payload is empty: `cargo build` / `cargo test --workspace` work
//! anywhere, and such an installer refuses to install ("no payload").
//!
//! It also embeds the app icon and the version info into `moku-setup.exe` (`build-support/winres.rs`).

use std::path::{Path, PathBuf};

#[path = "../build-support/winres.rs"]
mod winres;

const REQUIRED: [&str; 3] = ["moku.exe", "moku-settings.exe", "mokuctl.exe"];

fn main() {
    winres::embed("Moku Setup", "moku-setup");
    println!("cargo:rerun-if-env-changed=MOKU_SETUP_PAYLOAD");
    println!("cargo:rerun-if-changed=build.rs");
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let mut code = String::from("// Generated by build.rs.\npub static FILES: &[PayloadFile] = &[\n");
    if let Some(dir) = std::env::var_os("MOKU_SETUP_PAYLOAD").filter(|d| !d.is_empty()).map(PathBuf::from) {
        println!("cargo:rerun-if-changed={}", dir.display());
        let mut files = vec![];
        collect(&dir, &dir, &mut files);
        files.sort();
        for r in REQUIRED {
            assert!(files.iter().any(|(rel, _)| rel.eq_ignore_ascii_case(r)), "MOKU_SETUP_PAYLOAD ({}) has no {r}", dir.display());
        }
        for (i, (rel, path)) in files.iter().enumerate() {
            println!("cargo:rerun-if-changed={}", path.display());
            let data = std::fs::read(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
            let packed = compress(&data);
            let bin = out.join(format!("payload-{i}.lzms"));
            std::fs::write(&bin, &packed).expect("write payload");
            code.push_str(&format!(
                "    PayloadFile {{ path: {rel:?}, size: {}, compressed: true, data: include_bytes!({:?}) }},\n",
                data.len(),
                bin.display().to_string()
            ));
        }
    }
    code.push_str("];\n");
    std::fs::write(out.join("payload.rs"), code).expect("write payload.rs");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let rd = std::fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display()));
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect(root, &p, out);
        } else {
            let rel = p.strip_prefix(root).expect("prefix").to_string_lossy().replace('/', "\\");
            out.push((rel, p));
        }
    }
}

fn compress(data: &[u8]) -> Vec<u8> {
    use windows::Win32::Storage::Compression::*;
    unsafe {
        let mut h = COMPRESSOR_HANDLE::default();
        CreateCompressor(COMPRESS_ALGORITHM_LZMS, None, &mut h).expect("CreateCompressor");
        let mut out = vec![0u8; data.len() + data.len() / 8 + 64 * 1024];
        let mut n = 0usize;
        Compress(h, Some(data.as_ptr() as _), data.len(), Some(out.as_mut_ptr() as _), out.len(), &mut n).expect("Compress");
        let _ = CloseCompressor(h);
        out.truncate(n);
        out
    }
}
